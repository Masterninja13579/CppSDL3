int bgfxCubes()
{
    //Create window
    Application::Window window("Cubes");
    window.Create();

    std::cout << "Rendering with " << bgfx::getRendererName(bgfx::getRendererType()) << "\n";
    
    // Create vertex stream declaration.
    PosColorVertex::init();

    // Create static vertex buffer.
    bgfx::VertexBufferHandle vertexBuffer = bgfx::createVertexBuffer(
        // Static data can be passed with bgfx::makeRef
        bgfx::makeRef(s_cubeVertices, sizeof(s_cubeVertices)),
        PosColorVertex::ms_layout
    );

    bgfx::IndexBufferHandle indexBufferArray[BX_COUNTOF(s_ptState)];
    // Create static index buffer for triangle list rendering.
	indexBufferArray[0] = bgfx::createIndexBuffer(
        // Static data can be passed with bgfx::makeRef
        bgfx::makeRef(s_cubeTriList, sizeof(s_cubeTriList))
    );
	// Create static index buffer for triangle strip rendering.
	indexBufferArray[1] = bgfx::createIndexBuffer(
		// Static data can be passed with bgfx::makeRef
		bgfx::makeRef(s_cubeTriStrip, sizeof(s_cubeTriStrip))
	);
    // Create static index buffer for line list rendering.
	indexBufferArray[2] = bgfx::createIndexBuffer(
		// Static data can be passed with bgfx::makeRef
		bgfx::makeRef(s_cubeLineList, sizeof(s_cubeLineList))
	);
    // Create static index buffer for line strip rendering.
	indexBufferArray[3] = bgfx::createIndexBuffer(
		// Static data can be passed with bgfx::makeRef
		bgfx::makeRef(s_cubeLineStrip, sizeof(s_cubeLineStrip))
	);
    // Create static index buffer for point list rendering.
	indexBufferArray[4] = bgfx::createIndexBuffer(
		// Static data can be passed with bgfx::makeRef
		bgfx::makeRef(s_cubePoints, sizeof(s_cubePoints))
	);

    const bgfx::Memory* vShaderData = bgfx::alloc(vsCubesSize + 1);
    std::memcpy(vShaderData->data, vsCubes, vsCubesSize);
    vShaderData->data[vShaderData->size - 1] = '\0';

    const bgfx::Memory* fShaderData = bgfx::alloc(fsCubesSize + 1);
    std::memcpy(fShaderData->data, fsCubes, fsCubesSize);
    fShaderData->data[fShaderData->size - 1] = '\0';

    bgfx::ShaderHandle vertexShaderHandle = bgfx::createShader(vShaderData);
    //bgfx::ShaderHandle fragmentShaderHandle = BGFX_INVALID_HANDLE;
    bgfx::ShaderHandle fragmentShaderHandle = bgfx::createShader(fShaderData);
    bgfx::ProgramHandle shaderProgramHandle = bgfx::createProgram(
        vertexShaderHandle,
        fragmentShaderHandle,
        true
    );

    bx::Ticks tickStart = bx::getNow();
    bx::Ticks tickCurrent = tickStart;
    bx::Ticks tickLast = tickStart;

    int counter = 0;
    bool showDebugStats = false;
    int pt = 0;
    bool red = true;
    bool green = true;
    bool blue = true;
    bool alpha = true;

    //Create loop
    bool doStuff = true;
    while (doStuff)
    {
        //counter++;
        //std::cout << counter << "\n";

        // Set up time variables
        tickLast = tickCurrent;
        tickCurrent = bx::getNow();
        const float timeDelta = bx::toSeconds<float>(tickCurrent - tickLast);
        const float timeDuration = bx::toSeconds<float>(tickCurrent - tickStart);

        // Sleep if window is not visible
        if (window.GetSDLWindowFlags() & SDL_WINDOW_MINIMIZED)
        {
            SDL_Delay(10);
            continue;
        }

        // Events
        SDL_Event event;
        while (SDL_PollEvent(&event))
        {
            ImGui_ImplSDL3_ProcessEvent(&event);

            switch (event.type)
            {
                case SDL_EVENT_QUIT:
                    doStuff = false;
                    //window.Destroy();
                    break;
                case SDL_EVENT_WINDOW_CLOSE_REQUESTED:
                    doStuff = false;
                    //window.Destroy();
                    break;
                case SDL_EVENT_WINDOW_RESIZED:
                {
                    window.Refresh();
                    break;
                }
                case SDL_EVENT_KEY_DOWN:
                {
                    // Don't process keyboard events if ImGui has captured the keyboard
                    if (ImGui::GetIO().WantCaptureKeyboard)
                        break;

                    if (event.key.key == SDLK_SPACE)
                    {
                        showDebugStats = !showDebugStats;
                        bgfx::setDebug(showDebugStats ? BGFX_DEBUG_STATS : BGFX_DEBUG_TEXT);
                    }
                    break;
                }
                default: break;
            }
        }

        const bx::Vec3 at  = { 0.0f, 0.0f,   0.0f };
        const bx::Vec3 eye = { 0.0f, 0.0f, -35.0f };
        const int width = window.GetWidth();
        const int height = window.GetHeight();
        // Set view and projection matrix for view 0.
        {
           float view[16];
           bx::mtxLookAt(view, eye, at);

           float proj[16];
           bx::mtxProj(proj, 60.0f, float(width) / float(height), 0.1f, 100.0f, bgfx::getCaps()->homogeneousDepth);
           bgfx::setViewTransform(0, view, proj);

           // Set view 0 default viewport.
           bgfx::setViewRect(0, 0, 0, uint16_t(width), uint16_t(height));
        }

        // This dummy draw call is here to make sure that view 0 is cleared
        // if no other draw calls are submitted to view 0.
        bgfx::touch(0);

        bgfx::IndexBufferHandle indexBuffer = indexBufferArray[pt];
        uint64_t state = 0
            | (red ? BGFX_STATE_WRITE_R : 0)
            | (green ? BGFX_STATE_WRITE_G : 0)
            | (blue ? BGFX_STATE_WRITE_B : 0)
            | (alpha ? BGFX_STATE_WRITE_A : 0)
            | BGFX_STATE_WRITE_Z
            | BGFX_STATE_DEPTH_TEST_LESS
            | BGFX_STATE_CULL_CW
            | BGFX_STATE_MSAA
            | s_ptState[pt];

        // Submit 11x11 cubes.
        for (uint32_t y = 0; y < 11; ++y)
        {
            for (uint32_t x = 0; x < 11; ++x)
            {
                float mtx[16];
                bx::mtxRotateXY(mtx, timeDuration + x*0.21f, timeDuration + y*0.37f);
                mtx[12] = -15.0f + float(x)*3.0f;
                mtx[13] = -15.0f + float(y)*3.0f;
                mtx[14] = 0.0f;

                // Set model matrix for rendering.
                bgfx::setTransform(mtx);

                // Set vertex and index buffer.
                bgfx::setVertexBuffer(0, vertexBuffer);
                bgfx::setIndexBuffer(indexBuffer);

                // Set render states.
                bgfx::setState(state);

                // Submit primitive for rendering to view 0.
                bgfx::submit(0, shaderProgramHandle);
            }
        }

        // Advance to next frame. Rendering thread will be kicked to
        // process submitted rendering primitives.
        bgfx::frame();
    }

    // Cleanup
    for (uint32_t i = 0; i < BX_COUNTOF(indexBufferArray); ++i)
        bgfx::destroy(indexBufferArray[i]);
    bgfx::destroy(vertexBuffer);

    window.Destroy();

    return EXIT_SUCCESS;
}
